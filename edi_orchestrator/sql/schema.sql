-- =====================================================
-- EDI ORCHESTRATOR SCHEMA
-- Central Hub for routing EDI messages between countries
-- =====================================================

CREATE TABLE IF NOT EXISTS partners (
  id INT AUTO_INCREMENT PRIMARY KEY,
  gln VARCHAR(13) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  country_code VARCHAR(3) NOT NULL, -- ISO 3166-1 numeric (686, 788, etc.)
  target_url VARCHAR(255) NOT NULL, -- The webhook URL to receive EDI messages
  api_key VARCHAR(64), -- Optional: Key to authenticate requests to this partner
  status ENUM('ACTIVE', 'INACTIVE') DEFAULT 'ACTIVE',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_gln (gln)
);

CREATE TABLE IF NOT EXISTS transactions (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  transaction_ref VARCHAR(64) NOT NULL, -- Unique ID generated by the Hub or passed by Node
  sender_gln VARCHAR(13) NOT NULL,
  receiver_gln VARCHAR(13) NOT NULL,
  document_type VARCHAR(10) NOT NULL, -- ORDERS, ORDRSP, DESADV, INVOIC
  status ENUM('RECEIVED', 'FORWARDED', 'DELIVERED', 'FAILED', 'RETRY_QUEUED') DEFAULT 'RECEIVED',
  transport_mode ENUM('ORCHESTRATOR', 'P2P', 'P2P_SYNC') DEFAULT 'ORCHESTRATOR', -- To distinguish direct routing vs P2P sync logs
  error_message TEXT,
  payload_size INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP, -- Received At
  delivered_at DATETIME NULL,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_sender (sender_gln),
  INDEX idx_receiver (receiver_gln),
  INDEX idx_ref (transaction_ref),
  INDEX idx_created_at (created_at)
);

