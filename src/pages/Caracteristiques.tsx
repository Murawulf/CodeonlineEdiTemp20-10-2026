/**
 * Caracteristiques.tsx
 *
 * - Copy-paste ready.
 * - Props: { id_entite: number, isPrivileged?: boolean }
 *   `isPrivileged` should be passed the exact same way CatalogueComplet.tsx
 *   computes it for fiche produit: `[111, 999].includes(user.id_entite)`.
 *   It only controls what's SHOWN here (an "Approuver/Refuser" pair of
 *   buttons on pending fiches) - the real enforcement is server-side in
 *   server.js, so passing this wrong never grants real access, it just
 *   hides/shows buttons that would 403 anyway.
 *
 * A "caractéristique" lets an entity showcase a product or service that
 * doesn't fit the normal fiche produit record (no GTIN, no GPC category -
 * e.g. a service, a bespoke item, a one-off offer).
 *
 * The "identifiant" part of a fiche - its `code_identifiant` - is ALWAYS
 * generated by the server the moment a fiche is created: country prefix
 * (619) + id_entite + a number 0001..9999 (max 9999 fiches per entity).
 * There is no manual input for it anywhere; it never changes afterwards and
 * this form only ever *displays* it.
 *
 * Illustrations are stored exactly like fiche produit images
 * (/images/products/<file>, same folder, same mobile URL resolution) and are
 * uploaded automatically as soon as a file is chosen - no separate
 * "Upload" click needed, and "Valider" waits for any upload in progress.
 *
 * Mobile visibility (this is the important part to understand before
 * touching "Nature"):
 *   - nature = "fiche permanente"    -> needs an admin to approve it before
 *     it appears in the mobile app (approval_status: pending -> approved).
 *     Every save while pending sends it back to "pending" for re-review,
 *     unless a privileged/admin account is the one saving it.
 *   - nature = "fiche occasionnelle" -> never needs approval and NEVER
 *     appears in the mobile app, no matter what - it's a web-admin-only
 *     entry (drafts, internal notes, temporary things).
 *
 * Works with these API endpoints:
 * GET  /api/caracteristiques? id_entite,search,nature,status,page,limit
 * GET  /api/caracteristiques/:id
 * POST /api/caracteristiques   (server ALWAYS generates + returns code_identifiant)
 * PUT  /api/caracteristiques/:id  (code_identifiant is never re-generated)
 * DELETE /api/caracteristiques/:id
 * POST /api/caracteristiques/:id/approve   (privileged only)
 * POST /api/caracteristiques/:id/reject    (privileged only)
 * POST /api/caracteristiques/upload  (form field name = "file")
 */

// ------------------------- Types -------------------------
type ElementType = "varchar" | "number" | "integer" | "text" | "list";

interface ElementTechnique {
  nom: string;
  type: ElementType;
  options?: string[] | null; // if type === 'list'
  defaultValue?: string | null;
}

interface Illustration {
  filename: string;
  type: "image" | "video";
  url: string;
}

interface Caracteristique {
  id_carac?: number;
  nb_elements?: number;
  thumbnail?: string | null;
  id_entite: number;
  identification: string;
  brand?: string | null;
  // Generated by the server at creation - read-only everywhere in this
  // file, never part of what the user edits or sends.
  code_identifiant?: string | null;
  description_fr?: string;
  description_en?: string | null;
  description_ar?: string | null;
  nature?: "fiche occasionnelle" | "fiche permanente" | string;
  // Mobile visibility gate - only ever meaningful when nature is "fiche
  // permanente" (server sets/keeps this null for "fiche occasionnelle").
  // Set by the server; the form never edits it directly, only via the
  // Approuver/Refuser buttons in the table (privileged accounts only).
  approval_status?: "pending" | "approved" | "rejected" | null;
  utilite?: string;
  date_lancement?: string | null; // YYYY-MM-DD
  elements?: ElementTechnique[];
  illustrations?: Illustration[];
}

// ------------------------- Component -------------------------
// ------------------------- Media URL helper -------------------------
// Illustrations are stored as "/images/products/<file>" (same as fiche
// produit images - that is also what the mobile API resolves). In the WEB
// they are displayed through GET /api/caracteristiques/media/<file>, which
// goes through /api exactly like every axios call of this page, so the
// image shows even when the React front is served from another origin /
// proxy that does not forward /images/*.
const apiOrigin = (): string => {
  const base = (axios.defaults.baseURL || "").toString().trim();
  if (!base) return "";
  return base.replace(/\/+$/, "").replace(/\/api$/i, "");
};
const mediaSrc = (url?: string | null): string => {
  if (!url) return "";
  const u = String(url).trim();
  if (/^(https?:|blob:|data:)/i.test(u)) return u;
  const m = /^\/images\/(?:products|caracteristiques)\/([^/?#]+)$/.exec(u);
  if (m) return `${apiOrigin()}/api/caracteristiques/media/${encodeURIComponent(m[1])}`;
  return u;
};

